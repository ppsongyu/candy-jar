function abebeKaomoji(kind){
  const K = ABEBE_KAOMOJI, h = new Date().getHours();
  const night = h >= 22 || h < 6;
  if(night && Math.random() < ABK_SLEEPY_CHANCE) return randFrom(K.sleepy);
  if(K.mama.length && Math.random() < ABK_MAMA_CHANCE) return randFrom(K.mama);
  return randFrom(K[kind] || K.poke);
}
